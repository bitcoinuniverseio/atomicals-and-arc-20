#!/usr/bin/env node
/**
 * Generates standalone browser validators from the OpenAPI response schemas.
 *
 * The workbench validates live responses against the contract without
 * shipping the entire OpenAPI toolchain: Ajv compiles each response schema
 * into a standalone function at build time, and the generated module is
 * committed so generation stays deterministic.
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(here, '..')

const documents = ['arc20', 'atomicals-nfts-realms', 'marketplace-v1']
const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: true, strict: false, schemas: [] })
addFormats(ajv)

const registry = []
function rebaseRefs(schema, documentBase) {
  if (Array.isArray(schema)) return schema.map((entry) => rebaseRefs(entry, documentBase))
  if (schema && typeof schema === 'object') {
    const output = {}
    for (const [key, value] of Object.entries(schema)) {
      if (key === '$ref' && typeof value === 'string' && value.startsWith('#/')) {
        output[key] = `${documentBase}${value}`
      } else {
        output[key] = rebaseRefs(value, documentBase)
      }
    }
    return output
  }
  return schema
}

for (const name of documents) {
  const document = JSON.parse(readFileSync(resolve(ROOT, `contracts/openapi/${name}.json`), 'utf8'))
  const schemaId = `https://bitcoinuniverseio.github.io/atomicals-and-arc-20/contracts/openapi/${name}.json`
  ajv.addSchema({ $id: schemaId, components: document.components ?? {} })
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!['get', 'head'].includes(method)) continue
      for (const [statusCode, response] of Object.entries(operation.responses ?? {})) {
        const schema = response?.content?.['application/json']?.schema
        if (!schema) continue
        const key = `${name}:${method.toUpperCase()} ${path}:${statusCode}`
        const slug = key.replace(/[^\w-]+/g, '-')
        const id = `https://bitcoinuniverseio.github.io/atomicals-and-arc-20/validators/${slug}`
        ajv.addSchema({ $id: id, ...rebaseRefs(schema, schemaId) })
        registry.push({ key, id, document: name })
      }
    }
  }
}

const moduleCode = standaloneCode(
  ajv,
  Object.fromEntries(registry.map((entry, index) => [`validator${index}`, entry.id])),
)

const outDir = resolve(ROOT, 'site/src/generated')
mkdirSync(outDir, { recursive: true })
const header = `/*
 * Generated by scripts/generate-validators.mjs from the OpenAPI contracts.
 * Do not edit. Regenerate with npm run generate.
 */
export const validatorRegistry = ${JSON.stringify(registry, null, 2)}
`
// Ajv standalone emits CommonJS require() calls for format runtime helpers.
// Rewrite them as ES module imports so both Node and Vite consume the file
// directly. The transform is deterministic string surgery on known modules.
function asEsm(code) {
  const requires = [...code.matchAll(/require\("([^"]+)"\)/g)].map((match) => match[1])
  const imports = []
  let output = code
  for (const rawSpecifier of new Set(requires)) {
    const name = `__runtime${imports.length}`
    // Node ESM and Vite both resolve explicit .js files; Ajv emits extension-less runtime paths.
    const specifier = /\.(js|mjs)$/.test(rawSpecifier) ? rawSpecifier : `${rawSpecifier}.js`
    imports.push(`import ${name} from "${specifier}"`)
    output = output.split(`require("${rawSpecifier}")`).join(name)
  }
  return `${imports.length ? `${imports.join('\n')}\n` : ''}${output}`
}

writeFileSync(resolve(outDir, 'response-validators.mjs'), `${header}${asEsm(moduleCode)}`)

writeFileSync(
  resolve(outDir, 'validator-registry.json'),
  `${JSON.stringify({ generatedBy: 'scripts/generate-validators.mjs', validators: registry }, null, 2)}\n`,
)
process.stdout.write(`generated ${registry.length} standalone response validators\n`)
